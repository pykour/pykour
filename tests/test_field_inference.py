class TestFieldInferrer:
    """Tests for FieldInferrer class."""

    def test_infer_from_table_basic(self) -> None:
        """Infer fields from a basic Table definition."""
        inferrer = FieldInferrer()
        fields = inferrer.infer_from_table(UserTable)

        assert len(fields) == 6

        field_names = [f.name for f in fields]
        assert "id" in field_names
        assert "name" in field_names
        assert "email" in field_names
        assert "bio" in field_names
        assert "active" in field_names
        assert "created_at" in field_names

    def test_autoincrement_primary_key_is_auto_generated(self) -> None:
        """Autoincrement primary key is detected as auto-generated."""
        inferrer = FieldInferrer()
        fields = inferrer.infer_from_table(UserTable)

        id_field = next(f for f in fields if f.name == "id")
        assert id_field.is_primary_key is True
        assert id_field.is_auto_generated is True

    def test_created_at_is_auto_generated(self) -> None:
        """created_at column is detected as auto-generated."""
        inferrer = FieldInferrer()
        fields = inferrer.infer_from_table(UserTable)

        created_at_field = next(f for f in fields if f.name == "created_at")
        assert created_at_field.is_auto_generated is True

    def test_string_max_length_extraction(self) -> None:
        """String max_length is extracted from Column definition."""
        inferrer = FieldInferrer()
        fields = inferrer.infer_from_table(UserTable)

        name_field = next(f for f in fields if f.name == "name")
        assert name_field.max_length == 100

        email_field = next(f for f in fields if f.name == "email")
        assert email_field.max_length == 255

    def test_nullable_detection(self) -> None:
        """Nullable attribute is correctly detected."""
        inferrer = FieldInferrer()
        fields = inferrer.infer_from_table(UserTable)

        name_field = next(f for f in fields if f.name == "name")
        assert name_field.nullable is False

        bio_field = next(f for f in fields if f.name == "bio")
        assert bio_field.nullable is True

    def test_default_value_extraction(self) -> None:
        """Default values are correctly extracted."""
        inferrer = FieldInferrer()
        fields = inferrer.infer_from_table(UserTable)

        active_field = next(f for f in fields if f.name == "active")
        assert active_field.default is True

    def test_python_type_inference(self) -> None:
        """Python types are correctly inferred."""
        inferrer = FieldInferrer()
        fields = inferrer.infer_from_table(UserTable)

        id_field = next(f for f in fields if f.name == "id")
        assert id_field.python_type == "int"

        name_field = next(f for f in fields if f.name == "name")
        assert name_field.python_type == "str"

        active_field = next(f for f in fields if f.name == "active")
        assert active_field.python_type == "bool"


