"""Tests for field inference module."""

from __future__ import annotations


from pykour.db.migrations.table import Column, Table
from pykour.db.migrations.types import (
    Boolean,
    DateTime,
    Integer,
    String,
    Text,
)
from pykour.generators.field_inference import (
    AUTO_GENERATED_COLUMNS,
    COLUMN_TYPE_TO_STR,
    FieldInferrer,
)


class UserTable(Table):
    """Sample user table for testing."""

    __tablename__ = "users"

    id = Column(Integer(), primary_key=True, autoincrement=True)
    name = Column(String(100), nullable=False)
    email = Column(String(255), nullable=False)
    bio = Column(Text(), nullable=True)
    active = Column(Boolean(), default=True)
    created_at = Column(DateTime(), default="CURRENT_TIMESTAMP")


class ProductTable(Table):
    """Sample product table for testing."""

    __tablename__ = "products"

    id = Column(Integer(), primary_key=True, autoincrement=True)
    title = Column(String(200), nullable=False)
    description = Column(Text(), nullable=True)
    price = Column(Integer(), nullable=False)
    in_stock = Column(Boolean(), default=True)


