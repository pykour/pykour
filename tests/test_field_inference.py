class TestEmptyTable:
    """Tests for edge cases with minimal tables."""

    def test_table_with_only_id(self) -> None:
        """Table with only auto-generated id returns 'pass' for create."""

        class IdOnlyTable(Table):
            __tablename__ = "id_only"
            id = Column(Integer(), primary_key=True, autoincrement=True)

        inferrer = FieldInferrer()
        fields = inferrer.infer_from_table(IdOnlyTable)
        create_fields = inferrer.generate_create_fields(fields)
        update_fields = inferrer.generate_update_fields(fields)

        assert create_fields == "    pass"
        assert update_fields == "    pass"


